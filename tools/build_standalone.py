"""Build the no-server versions of Ecko Tone.

    python tools/build_standalone.py

Writes:
  web/standalone/tone-engine.js   the JavaScript engine, with catalog + blue-noise data filled in
  dist/ecko-tone.html             one self-contained page: double-click to use, works offline
  photoshop-plugin/tone-engine.js the same engine for the stand-alone Photoshop panel

The Python engine stays the reference: catalog data (presets, shirts, fonts, limits) and the
blue-noise table are read from it here, so the two versions can't drift apart.
"""

from __future__ import annotations

import base64
import json
import re
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from ecko.tone import engine as E  # noqa: E402
from ecko.tone import hybrid, noise  # noqa: E402
from ecko.tone.api import catalog as api_catalog  # noqa: E402

WEB = ROOT / "web"
STANDALONE = WEB / "standalone"


def catalog_data() -> dict:
    cat = api_catalog()
    cat["limits"]["max_megapixels"] = E.MAX_OUTPUT_PX // 1_000_000
    return {
        "api": cat,
        "styles_map": E.STYLES,
        "modes_map": E.MODES,
        "textures_map": E.TEXTURES,
        "targets_map": {k: {"label": v["label"], "lpi": list(v["lpi"]), "min_dot_mm": v["min_dot_mm"]}
                        for k, v in E.TARGETS.items()},
        "process_inks": [[n, list(c), a] for n, c, a in E.PROCESS_INKS],
        "shirt_fits_map": E.SHIRT_FITS,
        "fonts": [{"id": f.id, "name": f.name, "file": f.file} for f in E.FONTS.values()],
        "defaults": cat["defaults"],
        "diffusion": {k: [d, [list(t) for t in taps]] for k, (d, taps) in hybrid.DIFFUSION.items()},
    }


def blue_noise_b64() -> str:
    ranks = np.round(noise.blue_noise_tile() * 16384).astype("<u2")
    return base64.b64encode(ranks.tobytes()).decode()


def build_engine() -> str:
    src = (STANDALONE / "engine.src.js").read_text()
    js = src.replace("__CATALOG__", json.dumps(catalog_data(), separators=(",", ":")))
    js = js.replace("__BLUE_NOISE__", blue_noise_b64())
    header = "/* GENERATED by tools/build_standalone.py from engine.src.js: edit that file, then rebuild. */\n"
    return header + js


def build_page(engine_js: str) -> str:
    html = (WEB / "tone.html").read_text()
    css = (WEB / "styles.css").read_text() + "\n" + (WEB / "tone.css").read_text()
    fonts = {f.id: base64.b64encode((ROOT / "ecko" / "fonts" / f.file).read_bytes()).decode()
             for f in E.FONTS.values()}
    host = (STANDALONE / "host.js").read_text()
    shim = (STANDALONE / "shim.js").read_text()
    ui = (WEB / "tone.js").read_text()

    def script(code: str, attrs: str = "") -> str:
        return f"<script{attrs}>\n{code.replace('</script', '<\\/script')}\n</script>"

    html = re.sub(r'\s*<link rel="stylesheet" href="styles.css">\s*<link rel="stylesheet" href="tone.css">',
                  "\n  <style>\n" + css + "\n  </style>", html)
    # No server in this version: the embroidery page isn't available.
    html = re.sub(r'\s*<nav class="topActions">.*?</nav>',
                  '\n  <nav class="topActions"><span class="hint">Runs on your computer · works offline</span></nav>',
                  html, flags=re.S)
    worker_src = engine_js + "\n" + host
    bundle = "\n".join([
        script(json.dumps(fonts), ' type="application/json" id="eckoFonts"'),
        script(worker_src, ' type="text/plain" id="eckoWorkerSrc"'),
        script(engine_js), script(host), script(shim), script(ui),
    ])
    html = html.replace('<script src="tone.js"></script>', bundle)
    assert "tone.js\"" not in html and "styles.css" not in html
    return html


def build_plugin_zip() -> None:
    """dist/ecko-tone-photoshop-plugin.zip: the Photoshop panel folder, ready for UXP Developer Tool."""
    import zipfile
    src = ROOT / "photoshop-plugin"
    out = ROOT / "dist" / "ecko-tone-photoshop-plugin.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for name in ("manifest.json", "index.html", "index.js", "tone-engine.js", "README.md"):
            info = zipfile.ZipInfo(f"Ecko Tone/{name}", date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, (src / name).read_bytes())
    print(f"dist/ecko-tone-photoshop-plugin.zip  {out.stat().st_size / 1e3:.0f} KB")


def main() -> None:
    engine_js = build_engine()
    (STANDALONE / "tone-engine.js").write_text(engine_js)
    (ROOT / "photoshop-plugin" / "tone-engine.js").write_text(engine_js)
    if (STANDALONE / "host.js").exists() and (STANDALONE / "shim.js").exists():
        (ROOT / "dist").mkdir(exist_ok=True)
        page = build_page(engine_js)
        (ROOT / "dist" / "ecko-tone.html").write_text(page)
        print(f"dist/ecko-tone.html  {len(page) / 1e6:.2f} MB")
        build_plugin_zip()
    print("web/standalone/tone-engine.js, photoshop-plugin/tone-engine.js")


if __name__ == "__main__":
    main()
