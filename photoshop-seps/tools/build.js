#!/usr/bin/env node
'use strict';
// Bundles engine/*.js into engine.bundle.js (one file the panel loads in
// both Photoshop and the browser). `--check` fails if the bundle is stale.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'engine');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.js')).sort();
let out = '// Generated by tools/build.js from engine/*.js. Do not edit.\n(function (root) {\n  var defs = {}, cache = {};\n';
for (const f of files) {
  const name = './' + f.replace(/\.js$/, '');
  out += `  defs[${JSON.stringify(name)}] = function (module, exports, require) {\n${fs.readFileSync(path.join(dir, f), 'utf8')}\n  };\n`;
}
out += `  function req(name) {
    var key = name.replace(/\\.js$/, '');
    if (cache[key]) return cache[key].exports;
    if (!defs[key]) throw new Error('Module not in bundle: ' + name);
    var module = { exports: {} };
    cache[key] = module;
    defs[key](module, module.exports, req);
    return module.exports;
  }
  root.EckoEngine = req('./index');
})(typeof globalThis !== 'undefined' ? globalThis : window);
`;
const target = path.join(root, 'engine.bundle.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out) { console.error('engine.bundle.js is out of date: run `npm run build`'); process.exit(1); }
} else {
  fs.writeFileSync(target, out);
  console.log(`wrote engine.bundle.js (${files.length} modules, ${(out.length / 1024).toFixed(0)} KB)`);
}
